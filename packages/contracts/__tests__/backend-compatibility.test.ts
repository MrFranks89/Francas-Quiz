import { readFileSync } from 'node:fs';
import { CourseSchema } from '../src/course';

it('accepts the deterministic course generated by the backend pipeline', () => {
  const fixture = JSON.parse(readFileSync(new URL('../../../services/api/tests/fixtures/generated-course.json', import.meta.url), 'utf8'));
  expect(CourseSchema.safeParse(fixture).success).toBe(true);
});

// Bozza generata dopo lo scarto di 2 domande su 5 (services/api/tests/test_scarto_domande.py):
// lo scarto avviene prima della validazione del corso, quindi il risultato vale anche per il contratto TS.
it('accepts the course left after discarding questions that fail the quality rules', () => {
  const fixture = JSON.parse(readFileSync(new URL('../../../services/api/tests/fixtures/generated-course-con-scarti.json', import.meta.url), 'utf8'));
  const parsed = CourseSchema.safeParse(fixture);
  expect(parsed.success).toBe(true);
  expect(fixture.questions).toHaveLength(3);
  expect(fixture.modules[0].exam.passingScore).toBe(2);
});

it('rejects the same negative course corpus as the backend', () => {
  const base = new URL('../../../services/api/tests/fixtures/', import.meta.url);
  const fixture = JSON.parse(readFileSync(new URL('generated-course.json', base), 'utf8'));
  type Change = {path: (string | number)[]; value: unknown};
  // Un caso è una modifica singola ({path, value}) o più modifiche insieme ({changes: [...]}).
  const cases = JSON.parse(readFileSync(new URL('invalid-course-cases.json', base), 'utf8')) as (Change | {changes: Change[]})[];
  for (const testCase of cases) {
    const invalid = structuredClone(fixture);
    const changes = 'changes' in testCase ? testCase.changes : [testCase];
    for (const change of changes) {
      let target = invalid;
      for (const key of change.path.slice(0, -1)) target = target[key];
      target[change.path.at(-1)!] = change.value;
    }
    expect(CourseSchema.safeParse(invalid).success, changes.map(c => c.path.join('.')).join(' + ')).toBe(false);
  }
});
